/// A closed 5×7 bitmap font so text labels stay pixel-exact across machines.
/// Only uppercase A–Z, digits, and space; every other character is dropped.
public enum AnnotationFont {
    public static let width = 5
    public static let height = 7
    public static let advance = 6

    public static func glyphs(in string: String) -> [Character] {
        string.uppercased().compactMap { character in
            character == " " || rows[character] != nil ? character : nil
        }
    }

    public static func row(_ character: Character, _ index: Int) -> String? {
        guard (0..<height).contains(index) else { return nil }
        if character == " " { return "....." }
        return rows[character]?[index]
    }

